#!/usr/bin/env bash
# diary-staleness.sh — staleness detector for per-agent diaries.
#
# Sprint 46.6.2 — Agent OS Memory v2: Background Capture + Per-Agent Diaries.
# Visibility-only signal (never blocks). Lists agents whose diary.md is the
# placeholder *and* whose name appeared in a commit message under
# agent-os/<agent-name> in the last 30 days. Output written to:
#   agent-os/observations/diary-staleness-<date>.md
#
# Run nightly via the Scheduled QA System.
# Usage: bash agent-os/scripts/hooks/diary-staleness.sh

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../../.." && pwd)"
cd "$REPO_ROOT"

DATE=$(date +%Y-%m-%d)
OUT_DIR="agent-os/observations"
OUT="$OUT_DIR/diary-staleness-${DATE}.md"
mkdir -p "$OUT_DIR"

PLACEHOLDER_MARKER='<!-- diary will be appended by post-sprint-memory.sh -->'
SINCE="30 days ago"

{
  echo "# Diary Staleness Report — ${DATE}"
  echo
  echo "Agents with placeholder \`diary.md\` whose work surfaced in commits in the last 30 days."
  echo "Generated by \`agent-os/scripts/hooks/diary-staleness.sh\`."
  echo
  echo "| Agent | Diary | Recent commits |"
  echo "|---|---|---|"

  found=0
  for diary in agent-os/sub-agents/*/diary.md; do
    [ -f "$diary" ] || continue
    agent=$(basename "$(dirname "$diary")")
    [ "$agent" = "memories" ] && continue
    [ "$agent" = "agents" ] && continue
    [ "$agent" = "skills" ] && continue

    if grep -q "$PLACEHOLDER_MARKER" "$diary" 2>/dev/null; then
      # Placeholder — count recent commits that mention the agent.
      hits=$(git log --since="$SINCE" --pretty=format:'%h %s' 2>/dev/null \
        | grep -ic "\\b${agent}\\b" || true)
      if [ "${hits:-0}" -gt 0 ]; then
        echo "| ${agent} | placeholder | ${hits} commit(s) since ${SINCE/ago/days} |"
        found=$((found + 1))
      fi
    fi
  done

  echo
  if [ "$found" -eq 0 ]; then
    echo "_No stale diaries detected._"
  else
    echo "_${found} agent(s) flagged. Not blocking — visibility only._"
  fi
} > "$OUT"

echo "diary-staleness: wrote $OUT"
