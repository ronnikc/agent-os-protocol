/**
 * /train [agent] — turn user-supplied material into reviewable, reversible skills for an agent.
 *
 * Usage:
 *   node agent-os/scripts/train.mjs <agent-slug> --source <file> [--skill <name>] [--mode review|append] [--dry-run]
 *   node agent-os/scripts/train.mjs <agent-slug> --list
 *   node agent-os/scripts/train.mjs <agent-slug> --activate <skill>
 *   node agent-os/scripts/train.mjs <agent-slug> --deactivate <skill>
 *   node agent-os/scripts/train.mjs <agent-slug> --remove <skill>
 *
 * Safety contract (owned by the Training Agent):
 *  - Writes ONLY under agent-os/training/, agent-os/sub-agents/skills/trained/, agent-os/memories/trained/.
 *  - Never overwrites core rules or other agents.
 *  - Rejects any source containing secrets (keys/tokens/passwords/.env content).
 *  - Drafts are user-local by default (gitignored); activation is explicit.
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, rmSync, cpSync } from 'node:fs';
import { join, basename, resolve, extname, relative, sep } from 'node:path';
import { createHash } from 'node:crypto';

const ROOT = resolve(import.meta.dirname, '../..');
const AGENTS_DIR = join(ROOT, 'agent-os/sub-agents/agents');
const INBOX = join(ROOT, 'agent-os/training/inbox');
const REJECTED = join(ROOT, 'agent-os/training/rejected');
const TRAINED_SKILLS = join(ROOT, 'agent-os/sub-agents/skills/trained');

// Writes are confined to these roots.
const WRITE_ROOTS = [INBOX, REJECTED, TRAINED_SKILLS, join(ROOT, 'agent-os/memories/trained')];
const assertSafe = (p) => {
  const r = resolve(p);
  if (!WRITE_ROOTS.some((root) => r === root || r.startsWith(root + sep))) {
    throw new Error(`refusing to write outside training roots: ${r}`);
  }
  return r;
};

const SECRET_PATTERNS = [
  { name: 'private key block', re: /-----BEGIN [A-Z ]*PRIVATE KEY-----/ },
  { name: 'AWS access key id', re: /\bAKIA[0-9A-Z]{16}\b/ },
  { name: 'Anthropic/OpenAI-style key', re: /\bsk-(ant-)?[A-Za-z0-9_-]{20,}/ },
  { name: 'Slack token', re: /\bxox[baprs]-[A-Za-z0-9-]{10,}/ },
  { name: 'GitHub token', re: /\bgh[pousr]_[A-Za-z0-9]{30,}/ },
  { name: 'Bearer token', re: /\bBearer\s+[A-Za-z0-9._-]{20,}/ },
  { name: 'secret-looking assignment', re: /(?:^|\n)\s*(?:export\s+)?[A-Za-z0-9_]*(?:SECRET|TOKEN|PASSWORD|PASSWD|API[_-]?KEY|PRIVATE[_-]?KEY)[A-Za-z0-9_]*\s*[:=]\s*\S{8,}/i },
];
const detectSecrets = (text) => SECRET_PATTERNS.filter((p) => p.re.test(text)).map((p) => p.name);

const slugify = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 60);
const titleCase = (s) => s.replace(/[-_]+/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());
const today = () => new Date().toISOString().slice(0, 10);
const die = (msg, code = 1) => { console.error(`train: ${msg}`); process.exit(code); };

function parseArgs(argv) {
  const a = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const t = argv[i];
    if (t.startsWith('--')) {
      const key = t.slice(2);
      const next = argv[i + 1];
      if (next === undefined || next.startsWith('--')) a[key] = true;
      else { a[key] = next; i++; }
    } else a._.push(t);
  }
  return a;
}

function agentExists(slug) { return existsSync(join(AGENTS_DIR, `${slug}.md`)); }

function listAgents() {
  if (!existsSync(AGENTS_DIR)) return [];
  return readdirSync(AGENTS_DIR).filter((f) => f.endsWith('.md')).map((f) => f.replace('.md', ''));
}

function buildSkillMd(agent, skill, sourceBase, sourceText) {
  return `Title: ${titleCase(skill)}
Keywords: ${skill}, trained, ${agent}
Slug: ${skill}
Scope: Trained knowledge for the \`${agent}\` agent (source: ${sourceBase})
Last updated: ${today()}

> **Trained skill — DRAFT.** Generated by \`/train\` from \`${sourceBase}\` on ${today()}.
> Review and refine before activating. Provenance is in \`metadata.json\`. This skill is
> user-local by default and does **not** modify core rules or any other agent.

---

## Knowledge

${sourceText.trim()}

---

## How this was learned

Imported verbatim from the source document for review. Edit this skill to distil the source
into actionable guidance (rules, checklists, patterns) for the \`${agent}\` agent, then activate:

\`\`\`bash
node agent-os/scripts/train.mjs ${agent} --activate ${skill}
\`\`\`
`;
}

function cmdTrain(agent, args) {
  const source = args.source;
  if (!source || source === true) die('--source <file> is required to create a skill draft');
  const srcPath = resolve(String(source));
  if (!existsSync(srcPath)) die(`source not found: ${srcPath}`);
  const sourceText = readFileSync(srcPath, 'utf-8');
  const sourceBase = basename(srcPath);

  // Secret detection — refuse to train on sensitive material.
  const secrets = detectSecrets(sourceText);
  if (secrets.length) {
    console.error(`train: REJECTED — source appears to contain secrets: ${secrets.join(', ')}`);
    if (!args['dry-run']) {
      const dir = assertSafe(join(REJECTED, agent));
      mkdirSync(dir, { recursive: true });
      const skill = slugify(args.skill && args.skill !== true ? String(args.skill) : sourceBase.replace(extname(sourceBase), ''));
      writeFileSync(join(dir, `${skill}.json`), JSON.stringify({
        agent, skill, source: sourceBase, rejected_at: new Date().toISOString(),
        reason: 'secret-detected', findings: secrets,
      }, null, 2) + '\n');
      console.error(`train: logged rejection → ${relative(ROOT, join(dir, `${skill}.json`))}`);
    }
    process.exit(2);
  }

  const skill = slugify(args.skill && args.skill !== true ? String(args.skill) : sourceBase.replace(extname(sourceBase), ''));
  if (!skill) die('could not derive a skill name; pass --skill <name>');
  const target = join(INBOX, agent, skill);
  const sha = createHash('sha256').update(sourceText).digest('hex');

  const plan = [
    `${relative(ROOT, join(target, 'SKILL.md'))}`,
    `${relative(ROOT, join(target, 'metadata.json'))}`,
    `${relative(ROOT, join(target, 'references', sourceBase))}`,
  ];

  if (args['dry-run']) {
    console.log(`[dry-run] would create draft skill '${skill}' for agent '${agent}' (mode: ${args.mode || 'review'})`);
    plan.forEach((p) => console.log(`  + ${p}`));
    console.log('[dry-run] no files written.');
    return;
  }

  assertSafe(target);
  mkdirSync(join(target, 'references'), { recursive: true });
  writeFileSync(join(target, 'SKILL.md'), buildSkillMd(agent, skill, sourceBase, sourceText));
  writeFileSync(join(target, 'references', sourceBase), sourceText);
  writeFileSync(join(target, 'metadata.json'), JSON.stringify({
    agent, skill, status: 'review', mode: args.mode || 'review',
    source: { path: relative(ROOT, srcPath), filename: sourceBase, sha256: sha, bytes: Buffer.byteLength(sourceText) },
    created_at: new Date().toISOString(), generator: 'train.mjs',
  }, null, 2) + '\n');

  console.log(`train: created reviewable draft skill '${skill}' for agent '${agent}':`);
  plan.forEach((p) => console.log(`  + ${p}`));
  console.log(`train: review it, then activate with:\n  node agent-os/scripts/train.mjs ${agent} --activate ${skill}`);
}

function cmdList(agent) {
  const inboxDir = join(INBOX, agent);
  const trainedDir = join(TRAINED_SKILLS, agent);
  const drafts = existsSync(inboxDir) ? readdirSync(inboxDir).filter((d) => existsSync(join(inboxDir, d, 'SKILL.md'))) : [];
  const active = existsSync(trainedDir) ? readdirSync(trainedDir).filter((d) => existsSync(join(trainedDir, d, 'SKILL.md'))) : [];
  console.log(`Trained skills for '${agent}':`);
  console.log(`  drafts (review):  ${drafts.length ? drafts.join(', ') : '(none)'}`);
  console.log(`  active (trained): ${active.length ? active.join(', ') : '(none)'}`);
}

function cmdActivate(agent, skill) {
  if (!skill || skill === true) die('--activate <skill> requires a skill name');
  const src = join(INBOX, agent, String(skill));
  if (!existsSync(join(src, 'SKILL.md'))) die(`no draft '${skill}' for agent '${agent}' (run --list)`);
  const dest = assertSafe(join(TRAINED_SKILLS, agent, String(skill)));
  mkdirSync(join(TRAINED_SKILLS, agent), { recursive: true });
  cpSync(src, dest, { recursive: true });
  // flip status in metadata
  const metaPath = join(dest, 'metadata.json');
  if (existsSync(metaPath)) {
    const meta = JSON.parse(readFileSync(metaPath, 'utf-8'));
    meta.status = 'active'; meta.activated_at = new Date().toISOString();
    writeFileSync(metaPath, JSON.stringify(meta, null, 2) + '\n');
  }
  console.log(`train: activated '${skill}' for '${agent}' → ${relative(ROOT, dest)}`);
}

function cmdDeactivate(agent, skill) {
  if (!skill || skill === true) die('--deactivate <skill> requires a skill name');
  const dest = assertSafe(join(TRAINED_SKILLS, agent, String(skill)));
  if (!existsSync(dest)) die(`no active trained skill '${skill}' for '${agent}'`);
  rmSync(dest, { recursive: true, force: true });
  console.log(`train: deactivated '${skill}' for '${agent}' (draft remains in training/inbox for re-activation)`);
}

function cmdRemove(agent, skill) {
  if (!skill || skill === true) die('--remove <skill> requires a skill name');
  for (const base of [INBOX, TRAINED_SKILLS]) {
    const d = assertSafe(join(base, agent, String(skill)));
    if (existsSync(d)) rmSync(d, { recursive: true, force: true });
  }
  console.log(`train: removed '${skill}' for '${agent}' (draft + active)`);
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const agent = args._[0];
  if (!agent || args.help) {
    console.log('Usage: node agent-os/scripts/train.mjs <agent-slug> --source <file> [--skill <name>] [--dry-run]');
    console.log('       ... <agent-slug> [--list | --activate <skill> | --deactivate <skill> | --remove <skill>]');
    console.log(`Agents: ${listAgents().join(', ') || '(none discovered)'}`);
    process.exit(agent ? 0 : 1);
  }
  if (!agentExists(agent)) die(`unknown agent '${agent}'. Known: ${listAgents().join(', ')}`);

  if (args.list) return cmdList(agent);
  if (args.activate !== undefined) return cmdActivate(agent, args.activate);
  if (args.deactivate !== undefined) return cmdDeactivate(agent, args.deactivate);
  if (args.remove !== undefined) return cmdRemove(agent, args.remove);
  return cmdTrain(agent, args);
}

main();
